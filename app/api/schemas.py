from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field


class HealthResponse(BaseModel):
    """System health check response."""

    status: str = Field(default="healthy", example="healthy")
    service: str = Field(default="SAGE API", example="SAGE API")
    device: str = Field(example="cuda")
    base_model_loaded: bool = Field(example=True)
    active_crop: Optional[str] = Field(default=None, example="tomato")


class CropDetail(BaseModel):
    """Detailed crop metadata and checkpoint status."""

    crop_id: str
    display_name: str
    hf_repo: str
    checkpoint_subpath: str
    model_type: str
    adapter_name: str
    default_prompt: str
    loading_status: str
    classes_count: int
    known_classes: List[str]


class CropListResponse(BaseModel):
    """Response containing available crops, default prompts, and checkpoint mappings."""

    total_crops: int
    available_crops: List[str]
    crop_details: List[CropDetail]


class GPUStatusSchema(BaseModel):
    """GPU hardware and memory utilization."""

    available: bool
    device_name: Optional[str] = None
    total_memory_gb: Optional[float] = None
    allocated_memory_gb: Optional[float] = None
    reserved_memory_gb: Optional[float] = None


class ModelStatusResponse(BaseModel):
    """Current model manager and runtime state."""

    base_model: str
    active_crop: Optional[str] = None
    active_adapter: Optional[str] = None
    adapter_mode: str
    base_model_loaded: bool
    loaded_adapters: List[str]
    gpu_status: GPUStatusSchema
    mock_mode: bool


class PredictionInputInfo(BaseModel):
    """Echoed input prompt parameters."""

    prompt: str = Field(description="The prompt or instruction passed for inference")


class PredictionOutputInfo(BaseModel):
    """Structured diagnosis fields generated by the model."""

    response: str = Field(description="Actual model-generated response")
    class_name: Optional[str] = Field(default=None, description="Diagnosed condition name if identified")
    crop: Optional[str] = None
    disease_type: Optional[str] = None
    plant_organ: Optional[str] = None
    visual_symptoms: Optional[str] = None
    pathogen: Optional[str] = None
    matched_taxonomy_class: Optional[str] = None
    is_canonical_match: Optional[bool] = None
    attributes: Dict[str, Any] = Field(default_factory=dict)


class PredictionResponse(BaseModel):
    """Multimodal inference diagnosis response."""

    success: bool
    crop: str
    base_model: str
    active_adapter: str
    checkpoint: str
    input: PredictionInputInfo
    prediction: PredictionOutputInfo
    raw_output: str
    inference_time_seconds: float
    image_metadata: Optional[Dict[str, Any]] = None


class BatchItemResponse(BaseModel):
    """Result for an individual image within a batch diagnosis."""

    filename: str
    success: bool
    input: Optional[PredictionInputInfo] = None
    prediction: Optional[PredictionOutputInfo] = None
    raw_output: Optional[str] = None
    inference_time_seconds: Optional[float] = None
    error: Optional[str] = None


class BatchPredictionResponse(BaseModel):
    """Batch prediction response covering multiple images sequentially."""

    total_images: int
    successful_count: int
    failed_count: int
    crop: str
    total_time_seconds: float
    results: List[BatchItemResponse]


class ErrorResponse(BaseModel):
    """Standardized API error response format."""

    detail: str
    error_type: Optional[str] = None
